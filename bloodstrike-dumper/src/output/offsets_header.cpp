#include "pch.hpp"
#include "output/offsets_header.hpp"

#include "core/strings.hpp"

namespace dumper::output {

	OffsetsHeader::OffsetsHeader(const offsets::OffsetTable& offsets, DumpTarget target, std::optional<std::string> live_check)
		: offsets_(offsets), target_(std::move(target)), live_check_(std::move(live_check)) {}

	std::string OffsetsHeader::render() const {
		std::string out = render_banner();
		out += "#pragma once\n#include <cstdint>\n\nnamespace offsets {\n";

		std::string_view group;
		for (const auto& definition : offsets::kOffsetDefinitions) {
			if (definition.group != group) {
				group = definition.group;
				out += std::format("\n\t// {}\n", group);
			}
			out += render_offset(definition);
		}

		out += "\n} // namespace offsets\n";
		return out;
	}

	void OffsetsHeader::save(const std::filesystem::path& path) const {
		std::ofstream file(path, std::ios::binary | std::ios::trunc);
		if (!file) throw std::runtime_error(std::format("can't write {}", path.string()));
		file << render();
	}

	std::string OffsetsHeader::render_banner() const {
		const auto now = std::chrono::floor<std::chrono::seconds>(std::chrono::system_clock::now());
		const auto pid = target_.pid ? std::format(" (pid {})", *target_.pid) : std::string();

		std::string banner = "// Generated by bloodstrike-dumper\n";
		banner += std::format("// target:    {}{}\n", target_.name, pid);
		banner += std::format("// image:     base {}, size {}, timestamp 0x{:08X}\n",
			core::to_hex(target_.image_base), core::to_hex(target_.image_size), target_.pe_timestamp);
		banner += std::format("// dumped at: {:%Y-%m-%d %H:%M:%S}\n", now);
		if (live_check_) banner += std::format("// live:      {}\n", *live_check_);
		banner += std::format("// resolved:  {}/{}\n\n", offsets_.resolved_count(), offsets::kOffsetDefinitions.size());
		return banner;
	}

	std::string OffsetsHeader::render_offset(const offsets::OffsetDefinition& definition) const {
		if (const auto value = offsets_.value(definition.name))
			return std::format("\tconstexpr std::uintptr_t {} = {};\n", definition.name, core::to_hex(*value));

		if (offsets_.has_conflict(definition.name)) {
			std::string candidates;
			for (const auto& hit : offsets_.hits(definition.name))
				candidates += std::format("{}{} ({})", candidates.empty() ? "" : ", ", core::to_hex(hit.value), hit.source);
			return std::format("\t// constexpr std::uintptr_t {} = ?; // conflict: {}\n", definition.name, candidates);
		}

		return std::format("\t// constexpr std::uintptr_t {} = ?; // not found\n", definition.name);
	}

} // namespace dumper::output
